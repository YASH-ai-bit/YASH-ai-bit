import hashlib
from pathlib import Path
import subprocess
import tempfile
import unittest

from scripts.count_source_changes import content_exclusion, count_repository, path_exclusion


class SourceFilterTests(unittest.TestCase):
    def test_dependencies_are_rejected_even_with_source_extensions(self):
        for path in (
            "node_modules/react/index.js", "app/node_modules/x/main.ts",
            "venv312/Lib/site-packages/pkg/main.py", ".venv/lib/main.py",
            "lib/forge-std/src/Test.sol", "lib/openzeppelin-contracts/token/ERC20.sol",
            "contracts/lib/account-abstraction/contracts/core/EntryPoint.sol",
            "vendor/crate/src/lib.rs", "target/debug/build/main.rs",
            "dist/app.js", "src/__generated__/api.ts", "data/training.py",
        ):
            with self.subTest(path=path):
                self.assertIsNotNone(path_exclusion(path))

    def test_first_party_source_tests_and_monorepo_packages_are_kept(self):
        for path in (
            "src/main.rs", "contracts/Pool.sol", "tests/test_pool.py",
            "test/Pool.t.sol", "packages/wallet/src/index.ts", "lib/math.py",
            "scripts/deploy.sh", "web/index.html", "web/style.css",
        ):
            with self.subTest(path=path):
                self.assertIsNone(path_exclusion(path))

    def test_non_code_and_generated_filenames_are_rejected(self):
        for path in (
            "package-lock.json", "Cargo.lock", "README.md", "result.csv",
            "notebook.ipynb", "logo.svg", "image.png", "config.yaml",
            "client.min.js", "api.pb.go", "types.d.ts", "api_pb2.py",
            "lib/contracts/abis.ts", "lib/contracts/PoolABI.ts",
            "SUMMARY.html", "report.html", "htmlcov/index.html",
        ):
            with self.subTest(path=path):
                self.assertIsNotNone(path_exclusion(path))

    def test_generated_markers_must_appear_in_comments(self):
        self.assertIsNotNone(content_exclusion(b"// Code generated by tool. DO NOT EDIT.\nlet x = 1;\n"))
        self.assertIsNotNone(content_exclusion(b"# This file is generated automatically\nx=1\n"))
        self.assertIsNotNone(content_exclusion(b"/*\nThis file is generated with snarkJS.\n*/\npragma solidity ^0.8.0;\n"))
        self.assertIsNone(content_exclusion(b'const example = "@generated";\n'))
        self.assertIsNone(content_exclusion(b"// SPDX-License-Identifier: MIT\ncontract Pool {}\n"))

    def test_binary_and_lfs_pointers_are_rejected(self):
        self.assertIsNotNone(content_exclusion(b"abc\0def"))
        self.assertIsNotNone(content_exclusion(b"version https://git-lfs.github.com/spec/v1\n"))


class GitHistoryTests(unittest.TestCase):
    def test_full_history_excludes_packages_generated_files_merges_and_pure_renames(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            source = root / "source"
            source.mkdir()

            def git(*args):
                return subprocess.run(["git", "-C", str(source), *args], capture_output=True,
                                      text=True, check=True).stdout.strip()

            def write(path, text):
                target = source / path
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")

            def commit(message):
                git("add", ".")
                git("commit", "-m", message)
                return git("rev-parse", "HEAD")

            git("init", "-b", "main")
            git("config", "user.name", "Fixture")
            git("config", "user.email", "fixture@example.test")
            git("config", "core.autocrlf", "false")
            write("src/main.py", "print('hello')\n")
            write("node_modules/pkg/main.py", "package_line\n" * 500)
            write("venv312/Lib/site-packages/pkg.py", "package_line\n" * 500)
            write("src/api.ts", "// Code generated by tool. DO NOT EDIT.\nlet x=1;\n")
            write("package-lock.json", "{}\n")
            first = commit("initial")
            write("src/main.py", "print('hello')\nprint('world')\n")
            write("src/api.ts", "// Code generated by tool. DO NOT EDIT.\nlet x=2;\n")
            second = commit("edit")
            git("mv", "src/main.py", "src/run.py")
            renamed = commit("rename")
            git("checkout", "-b", "feature")
            write("src/feature.py", "value=1")
            feature = commit("feature")
            git("checkout", "main")
            git("merge", "--no-ff", "feature", "-m", "merge feature")
            merged = git("rev-parse", "HEAD")
            git("commit", "--allow-empty", "-m", "empty")
            empty = git("rev-parse", "HEAD")
            write("src/run.py", "print('world')\n")
            removed = commit("delete a source line")
            cache = root / "cache"
            bare = cache / "git" / hashlib.sha256(b"fixture/repo").hexdigest()[:16]
            bare.parent.mkdir(parents=True)
            subprocess.run(["git", "clone", "--bare", str(source), str(bare)],
                           capture_output=True, check=True)
            result = count_repository("fixture/repo", [removed, empty, merged, feature, renamed, second, first], cache)
            self.assertEqual(result["commits_checked"], 7)
            self.assertEqual(result["merges_skipped"], 1)
            self.assertEqual(result["additions"], 3)
            self.assertEqual(result["deletions"], 1)
            self.assertEqual(len(result["source_commits"]), 4)
            self.assertTrue(result["net_verified"])


if __name__ == "__main__":
    unittest.main()
