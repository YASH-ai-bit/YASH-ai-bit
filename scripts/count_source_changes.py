"""Count source changes in GitHub-authored commits without counting packages.

Requires Python 3.10+, Git, and an authenticated GitHub CLI. Repositories are
read as bare, partial clones in a separate cache; their code is never executed.
Run: python scripts/count_source_changes.py --login YASH-ai-bit --as-of 2026-10-22
"""

from __future__ import annotations

import argparse
import collections
import concurrent.futures
import datetime as dt
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import subprocess
import tempfile


SOURCE_SUFFIXES = frozenset("""
    .sol .move .rs .go .c .h .cc .hh .cpp .hpp .cxx .hxx
    .py .js .jsx .mjs .cjs .ts .tsx .vue .svelte .html .htm
    .css .scss .sass .less .java .kt .kts .swift .m .mm .cs
    .fs .fsx .rb .php .phtml .ex .exs .erl .hrl .hs .lhs
    .scala .sc .clj .cljs .cljc .lua .pl .pm .r .jl .dart
    .sh .bash .zsh .fish .ps1 .psm1 .sql .prisma .proto
    .graphql .gql .wgsl .glsl .vert .frag .vy .yul .cairo
""".split())

EXCLUDED_DIRS = frozenset("""
    node_modules bower_components vendor vendors vendored third_party
    third-party thirdparty external externals deps dependencies
    site-packages dist-packages __pypackages__ .pnpm .yarn .npm
    target dist build builds out artifacts cache caches coverage
    .next .nuxt .output .svelte-kit .astro .turbo .cache
    .parcel-cache .webpack .vite .vercel .netlify __pycache__
    generated __generated__ typechain typechain-types abis abi
    bin obj packages.lock .git .idea .vscode data dataset datasets
    test-results playwright-report lcov-report htmlcov
""".split())

VENDOR_NAMES = frozenset("""
    forge-std openzeppelin-contracts openzeppelin-contracts-upgradeable
    openzeppelin @openzeppelin solmate solady ds-test chainlink
    chainlink-brownie-contracts foundry-devops foundry-upgrades
    murky erc721a prb-math v4-core v4-periphery v3-core v3-periphery
    uniswap uniswap-v2 uniswap-v3 @uniswap @chainlink account-abstraction
    safe-contracts safe-smart-account risc0-ethereum snarkjs
""".split())

ENV_DIR = re.compile(r"^\.?((?:virtual)?env|venv)(?:[-_.]?\d[\d._-]*)?$", re.I)
GENERATED_NAME = re.compile(
    r"(?:\.min\.(?:js|css)$|\.bundle\.[cm]?js$|\.d\.[cm]?ts$|"
    r"\.map$|\.pb\.[^/]+$|_pb2(?:_grpc)?\.py$|"
    r"[._-](?:generated|gen|designer|g)\.[^/]+$)", re.I
)
ABI_NAME = re.compile(r"(?:^abi(?:[._-]|$)|abis?$)", re.I)
REPORT_NAME = re.compile(r"^(?:summary|report|coverage|lcov|test-results)(?:[._-].*)?\.html?$", re.I)
GENERATED_HEADER = re.compile(
    rb"(?:@generated\b|<auto-generated|code generated[^\r\n]*do not edit|"
    rb"automatically generated|auto[- ]?generated file|this file (?:is|was) generated|"
    rb"generated (?:by|with) (?:protoc|abigen|typechain|graphql|prisma)|"
    rb"openzeppelin contracts \(last updated)", re.I
)
SHA = re.compile(rb"^[0-9a-f]{40}$")


def path_exclusion(path: str) -> str | None:
    parts = PurePosixPath(path).parts
    if not parts:
        return "non-source"
    directories = [part.lower() for part in parts[:-1]]
    if any(part in EXCLUDED_DIRS or ENV_DIR.fullmatch(part) for part in directories):
        return "dependency/build/data directory"
    if any(part in VENDOR_NAMES for part in directories):
        return "third-party library"
    name = parts[-1].lower()
    if REPORT_NAME.fullmatch(name):
        return "HTML report"
    if ABI_NAME.search(PurePosixPath(name).stem):
        return "ABI data"
    if GENERATED_NAME.search(name):
        return "generated filename"
    if PurePosixPath(name).suffix not in SOURCE_SUFFIXES:
        return "non-source"
    return None


def content_exclusion(content: bytes) -> str | None:
    if b"\0" in content:
        return "binary"
    if content.startswith(b"version https://git-lfs.github.com/spec/v1"):
        return "LFS pointer"
    comments = re.findall(rb"/\*.*?\*/|<!--.*?-->|(?m:^\s*(?://|#|--)[^\r\n]*)",
                          content[:16384], flags=re.S)
    if any(GENERATED_HEADER.search(comment) for comment in comments):
        return "generated/third-party header"
    return None


def gh_query(query: str, variables: dict | None = None) -> dict:
    result = subprocess.run(
        ["gh", "api", "graphql", "--input", "-"],
        input=json.dumps({"query": query, "variables": variables or {}}),
        text=True, capture_output=True, check=True,
    )
    response = json.loads(result.stdout)
    if response.get("errors"):
        raise RuntimeError(response["errors"])
    return response["data"]


def discover(login: str, as_of: str) -> tuple[dict, dict]:
    user = gh_query(
        "query($login:String!){user(login:$login){id login createdAt}}", {"login": login}
    )["user"]
    repos = {}
    for field in ("repositories", "repositoriesContributedTo"):
        after = None
        while True:
            options = "ownerAffiliations:OWNER" if field == "repositories" else (
                "includeUserRepositories:true,contributionTypes:[COMMIT,ISSUE,PULL_REQUEST,REPOSITORY]"
            )
            query = """query($login:String!,$after:String){user(login:$login){
              FIELD(first:100,after:$after,OPTIONS){
                pageInfo{hasNextPage endCursor}
                nodes{nameWithOwner defaultBranchRef{name}}
              }}}""".replace("FIELD", field).replace("OPTIONS", options)
            connection = gh_query(query, {"login": login, "after": after})["user"][field]
            repos.update({r["nameWithOwner"]: r for r in connection["nodes"]})
            if not connection["pageInfo"]["hasNextPage"]:
                break
            after = connection["pageInfo"]["endCursor"]
    for year in range(int(user["createdAt"][:4]), int(as_of[:4]) + 1):
        query = """query($login:String!,$from:DateTime!,$to:DateTime!){user(login:$login){
          contributionsCollection(from:$from,to:$to){
            commitContributionsByRepository(maxRepositories:100){
              repository{nameWithOwner defaultBranchRef{name}}
            }
          }}}"""
        end = min(f"{year}-12-31", as_of) + "T23:59:59Z"
        contributions = gh_query(query, {
            "login": login, "from": f"{year}-01-01T00:00:00Z", "to": end,
        })["user"]["contributionsCollection"]["commitContributionsByRepository"]
        if len(contributions) >= 100:
            raise RuntimeError("GitHub's yearly repository discovery limit was reached")
        repos.update({c["repository"]["nameWithOwner"]: c["repository"] for c in contributions})
    histories = {}
    for number, (name, repo) in enumerate(sorted(repos.items()), 1):
        if not repo["defaultBranchRef"]:
            continue
        owner, short_name = name.split("/")
        after, commits = None, []
        while True:
            query = """query($owner:String!,$name:String!,$id:ID!,$after:String,$until:GitTimestamp!){
              repository(owner:$owner,name:$name){defaultBranchRef{target{... on Commit{
                history(first:100,after:$after,author:{id:$id},until:$until){
                  pageInfo{hasNextPage endCursor} nodes{oid additions deletions}
                }
              }}}}}"""
            history = gh_query(query, {
                "owner": owner, "name": short_name, "id": user["id"],
                "after": after, "until": as_of + "T23:59:59Z",
            })["repository"]["defaultBranchRef"]["target"]["history"]
            commits.extend(history["nodes"])
            if not history["pageInfo"]["hasNextPage"]:
                break
            after = history["pageInfo"]["endCursor"]
        histories[name] = commits
        print(f"Discovered histories: {number}/{len(repos)}", flush=True)
    return {"user": user, "repositories": repos}, histories


def git_command(repo: Path | None, *arguments: str, data: bytes | None = None) -> bytes:
    command = ["git", "-c", "credential.helper=", "-c", "credential.helper=!gh auth git-credential",
               "-c", "fetch.recurseSubmodules=false", "-c", "fetch.negotiationAlgorithm=noop", "-c", "gc.auto=0"]
    if repo is not None:
        command.extend(["-C", str(repo)])
    command.extend(arguments)
    env = dict(os.environ, GIT_TERMINAL_PROMPT="0", GCM_INTERACTIVE="Never")
    result = subprocess.run(command, input=data, capture_output=True, env=env, timeout=180)
    if result.returncode:
        raise RuntimeError(result.stderr.decode(errors="replace"))
    return result.stdout


def read_raw(data: bytes) -> dict[str, list[tuple[str, str, str, str, str]]]:
    fields = iter(data.split(b"\0"))
    commits = {}
    current = None
    for field in fields:
        if not field.strip():
            continue
        if SHA.fullmatch(field.strip()):
            current = field.strip().decode()
            commits[current] = []
        elif field.startswith(b":") and current is not None:
            old_mode, new_mode, old_oid, new_oid, status = field[1:].decode().split()
            path = next(fields).decode("utf-8", errors="surrogateescape")
            commits[current].append((path, old_mode, new_mode, old_oid, new_oid))
        else:
            raise RuntimeError("Unrecognized Git raw diff record")
    return commits


def read_numstat(data: bytes) -> list[tuple[str, str, str, int, int]]:
    fields = iter(data.split(b"\0"))
    result, current = [], None
    for field in fields:
        if not field.strip():
            continue
        if SHA.fullmatch(field.strip()):
            current = field.strip().decode()
            continue
        added, deleted, path = field.split(b"\t", 2)
        if path:
            old_path = new_path = path.decode("utf-8", errors="surrogateescape")
        else:
            old_path = next(fields).decode("utf-8", errors="surrogateescape")
            new_path = next(fields).decode("utf-8", errors="surrogateescape")
        if added == b"-" or deleted == b"-":
            continue
        if current is None:
            raise RuntimeError("Missing commit for numstat record")
        result.append((current, old_path, new_path, int(added), int(deleted)))
    return result


def read_objects(repo: Path, ordered: list[str]):
    raw = git_command(repo, "--no-lazy-fetch", "cat-file", "--batch",
                      data=("\n".join(ordered) + "\n").encode())
    offset = 0
    for oid in ordered:
        end = raw.index(b"\n", offset)
        header = raw[offset:end].split()
        if len(header) != 3 or header[0].decode() != oid:
            raise RuntimeError("Missing Git object")
        size = int(header[2])
        offset = end + 1
        yield oid, header[1].decode(), raw[offset:offset + size]
        offset += size + 1


def read_blobs(repo: Path, oids: set[str]) -> dict[str, tuple[str | None, int]]:
    if not oids:
        return {}
    ordered = sorted(oids)
    check = git_command(repo, "--no-lazy-fetch", "cat-file", "--batch-check=%(objectname) %(objecttype)",
                        data=("\n".join(ordered) + "\n").encode())
    missing = [row.split()[0].decode() for row in check.splitlines() if row.endswith(b" missing")]
    # Explicitly fetch missing source blobs in batches. Do not fetch the
    # dependency blobs that a partial clone deliberately omitted.
    for start in range(0, len(missing), 400):
        git_command(repo, "fetch", "--filter=blob:none", "--no-tags", "--no-write-fetch-head", "origin", "--stdin",
                    data=("\n".join(missing[start:start + 400]) + "\n").encode())
    statistics = {}
    for oid, kind, content in read_objects(repo, ordered):
        if kind != "blob":
            raise RuntimeError("Expected a source blob")
        lines = content.count(b"\n") + int(bool(content) and not content.endswith(b"\n"))
        statistics[oid] = (content_exclusion(content), lines)
    return statistics


def count_repository(name: str, commits: list[str], cache: Path) -> dict:
    repo = cache / "git" / hashlib.sha256(name.encode()).hexdigest()[:16]
    if not repo.exists():
        repo.parent.mkdir(parents=True, exist_ok=True)
        git_command(None, "clone", "--bare", "--filter=blob:none", "--single-branch", "--no-tags",
                    "https://github.com/" + name + ".git", str(repo))
    # Fetch the selected commit IDs too, so a cached clone cannot silently omit
    # newly discovered commits or commits made unreachable by a force push.
    check = git_command(repo, "--no-lazy-fetch", "cat-file", "--batch-check=%(objectname) %(objecttype)",
                        data=("\n".join(commits) + "\n").encode())
    missing_commits = [row.split()[0].decode() for row in check.splitlines() if row.endswith(b" missing")]
    if missing_commits:
        git_command(repo, "fetch", "--filter=blob:none", "--no-tags", "--no-write-fetch-head",
                    "origin", "--stdin", data=("\n".join(missing_commits) + "\n").encode())
    merges = set()
    for oid, kind, content in read_objects(repo, commits):
        if kind != "commit":
            raise RuntimeError("Expected a commit object")
        parents = [line for line in content.partition(b"\n\n")[0].splitlines() if line.startswith(b"parent ")]
        if len(parents) > 1:
            merges.add(oid)
    expected = set(commits) - merges
    commit_input = ("\n".join(sha for sha in commits if sha not in merges) + "\n").encode()
    raw = read_raw(git_command(repo, "diff-tree", "--stdin", "--root", "-r", "--no-renames",
                               "--always", "--raw", "-z", "--no-ext-diff", "--no-textconv", data=commit_input))
    if set(raw) != expected:
        raise RuntimeError("Incomplete non-merge commit coverage")
    excluded, paths, objects = collections.Counter(), set(), set()
    entries = {}
    for sha, changes in raw.items():
        for path, old_mode, new_mode, old_oid, new_oid in changes:
            reason = path_exclusion(path)
            if reason:
                excluded[reason] += 1
                continue
            if any(mode not in {"000000", "100644", "100755"} for mode in (old_mode, new_mode)):
                excluded["symlink/submodule"] += 1
                continue
            paths.add(path)
            entries[sha, path] = (old_oid, new_oid)
            objects.update(oid for oid in (old_oid, new_oid) if oid != "0" * 40)
    blob_stats = read_blobs(repo, objects)
    expected_net = 0
    for old_oid, new_oid in entries.values():
        old = blob_stats.get(old_oid, (None, 0))
        new = blob_stats.get(new_oid, (None, 0))
        if old[0] is None and new[0] is None:
            expected_net += new[1] - old[1]
    # Limit the diff to literal, already-reviewed source paths. This also avoids
    # Git downloading package blobs while calculating rename similarity.
    paths = sorted(paths)
    additions = deletions = 0
    changes, source_commits = [], set()
    # Stay below Windows' command-line limit. Rename detection is per batch;
    # net totals remain correct even when a rename crosses two batches.
    batches, batch, length = [], [], 0
    for path in paths:
        if batch and length + len(path) > 16000:
            batches.append(batch)
            batch, length = [], 0
        batch.append(":(literal)" + path)
        length += len(path) + 20
    if batch:
        batches.append(batch)
    for batch in batches:
        data = git_command(repo, "diff-tree", "--stdin", "--root", "-r", "--find-renames",
                           "--always", "--numstat", "-z", "--no-ext-diff", "--no-textconv", "--", *batch,
                           data=commit_input)
        for sha, old_path, new_path, added, deleted in read_numstat(data):
            oids = set(entries.get((sha, old_path), ())) | set(entries.get((sha, new_path), ()))
            if not oids:
                continue
            reasons = {blob_stats[oid][0] for oid in oids if oid != "0" * 40 and blob_stats[oid][0]}
            if reasons:
                excluded[sorted(reasons)[0]] += 1
                continue
            additions += added
            deletions += deleted
            if added or deleted:
                source_commits.add(sha)
            changes.append({"commit": sha, "path": new_path, "additions": added, "deletions": deleted})
    if additions - deletions != expected_net:
        raise RuntimeError("Git diff totals disagree with the independent before/after source-line count")
    return {"additions": additions, "deletions": deletions, "net_verified": True,
            "source_commits": sorted(source_commits),
            "merges_skipped": len(merges), "excluded": dict(excluded), "changes": changes,
            "commits_checked": len(commits)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--login", default="YASH-ai-bit")
    parser.add_argument("--as-of", default=dt.date.today().isoformat())
    parser.add_argument("--cache-dir", type=Path, default=Path(tempfile.gettempdir()) / "yash-bio-refresh")
    parser.add_argument("--reuse-snapshot", action="store_true", help="Reuse metadata.json and histories.json in the cache")
    args = parser.parse_args()
    dt.date.fromisoformat(args.as_of)
    cache = args.cache_dir.resolve()
    cache.mkdir(parents=True, exist_ok=True)
    if args.reuse_snapshot:
        metadata = json.loads((cache / "metadata.json").read_text(encoding="utf-8"))
        histories = json.loads((cache / "histories.json").read_text(encoding="utf-8"))
    else:
        metadata, histories = discover(args.login, args.as_of)
        (cache / "metadata.json").write_text(json.dumps(metadata), encoding="utf-8")
        (cache / "histories.json").write_text(json.dumps(histories), encoding="utf-8")
    if metadata["user"]["login"].lower() != args.login.lower():
        raise RuntimeError("Cached snapshot belongs to another user")
    seen, work = set(), []
    for name, history in sorted(histories.items()):
        commits = []
        for commit in history:
            if commit["oid"] not in seen:
                seen.add(commit["oid"])
                commits.append(commit["oid"])
        if commits:
            work.append((name, commits))
    audit, excluded, errors = {}, collections.Counter(), {}
    totals = {"additions": 0, "deletions": 0, "merges_skipped": 0, "commits_checked": 0}
    source_commits = set()
    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
        futures = {pool.submit(count_repository, name, commits, cache): name for name, commits in work}
        for future in concurrent.futures.as_completed(futures):
            name = futures[future]
            try:
                result = future.result()
            except Exception as error:
                errors[name] = str(error)
                (cache / "source-errors.json").write_text(json.dumps(errors), encoding="utf-8")
                print(f"Source history failed: {len(errors)}; details saved in the private cache", flush=True)
                continue
            audit[name] = result
            for key in totals:
                totals[key] += result[key]
            source_commits.update(result["source_commits"])
            excluded.update(result["excluded"])
            (cache / "source-audit.json").write_text(json.dumps(audit), encoding="utf-8")
            print(f"Checked source histories: {len(audit)}/{len(work)}", flush=True)
    if errors:
        raise RuntimeError(f"{len(errors)} repository histories failed; see {cache / 'source-errors.json'}")
    if totals["commits_checked"] != len(seen):
        raise RuntimeError("Commit coverage mismatch")
    report = {"login": args.login, "as_of": args.as_of, "repositories_checked": len(work),
              **totals, "source_commits": len(source_commits),
              "net_lines": totals["additions"] - totals["deletions"],
              "net_verified": all(result["net_verified"] for result in audit.values()),
              "excluded_changes": dict(excluded)}
    (cache / "source-stats.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
